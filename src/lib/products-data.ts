function getCategory(price: number): Product['category'] {
  if (price < 60000) return 'budget';
  if (price < 100000) return 'gaming';
  if (price < 180000) return 'performance';
  if (price < 300000) return 'premium';
  return 'ultra';
}

function formatPrice(price: number): string {
  return new Intl.NumberFormat('ru-RU').format(price) + ' ₽';
}

function createSlug(title: string): string {
  return title.toLowerCase().replace(/\s+/g, '-').replace('va-', '');
}


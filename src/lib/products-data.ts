// Helper functions
export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getProductsByCategory(category: Product['category']): Product[] {
  return products.filter((p) => p.category === category);
}

export function getFeaturedProducts(count: number = 6): Product[] {
  // Return a mix of products from different categories
  const budget = products.filter(p => p.category === 'budget').slice(0, 1);
  const gaming = products.filter(p => p.category === 'gaming').slice(0, 2);
  const performance = products.filter(p => p.category === 'performance').slice(0, 2);
  const premium = products.filter(p => p.category === 'premium').slice(0, 1);

  return [...budget, ...gaming, ...performance, ...premium].slice(0, count);
}

export function searchProducts(query: string): Product[] {
  const lowercaseQuery = query.toLowerCase();
  return products.filter((p) =>
    p.title.toLowerCase().includes(lowercaseQuery) ||
    p.cpu.toLowerCase().includes(lowercaseQuery) ||
    p.gpu.toLowerCase().includes(lowercaseQuery)
  );
}

